#!/usr/bin/env python3
"""Aggregate per-seed evaluation JSONs into seed-level summary statistics.

For every metric it reports mean, std, min/max, and a nonparametric bootstrap
95% confidence interval over seeds for learned methods. Deterministic methods
must be declared with ``--deterministic``: repeated seeds are then treated as
replication checks rather than independent samples and no seed confidence
interval is reported.

This is a supplemental raw-JSON diagnostic. The final campaign's primary
investor-only tables are generated by ``generate_detailed_metrics.py`` and
``compare_campaign_methods.py``.
"""

from __future__ import annotations

import argparse
import csv
import glob
import json
import os
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np


PROJECT_ROOT = Path(__file__).resolve().parents[1]

DEFAULT_METRICS = [
    "sleeve_trading_ruined",
    "sleeve_trading_sharpe_ratio",
    "sleeve_trading_sharpe_ratio_raw",
    "sleeve_trading_daily_sharpe_ratio",
    "sleeve_trading_daily_hac7_sharpe_ratio",
    "sleeve_trading_daily_hac7_zero_rf_sharpe_ratio",
    "sleeve_trading_annualized_geometric_return_pct",
    "sleeve_trading_complete_daily_window_return_pct",
    "sleeve_trading_final_partial_day_return_pct",
    "sleeve_trading_max_drawdown_pct",
    "sleeve_trading_return_pct",
    "sleeve_trading_gain_usd",
    "sleeve_trading_volatility",
    "sleeve_mean_abs_exposure_dkk",
    "sleeve_exposure_turnover_x_sleeve",
    "sleeve_total_trading_costs_usd",
    "sleeve_total_volume_transaction_fees_usd",
    "sleeve_total_market_access_fees_usd",
    "sleeve_total_impact_costs_usd",
    "sleeve_total_collateral_funding_costs_usd",
    "sleeve_gross_trading_gain_usd",
    "sleeve_friction_share_of_gross_gain",
    "sleeve_settlement_event_count",
    "sleeve_settlement_pnl_hit_rate",
    "sleeve_settlement_pnl_mean_dkk",
]


def _seed_from_path(path: str) -> Optional[int]:
    match = re.search(r"seed(\d+)", str(path))
    return int(match.group(1)) if match else None


def _extract_tier_metrics(payload: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    tiers = payload.get("tiers")
    if isinstance(tiers, dict):
        for value in tiers.values():
            if isinstance(value, dict):
                return value
    return payload if isinstance(payload, dict) else None


def _metric_value(tier_metrics: Dict[str, Any], name: str) -> Optional[float]:
    sleeve = tier_metrics.get("sleeve_metrics")
    source = sleeve if isinstance(sleeve, dict) and name in sleeve else tier_metrics
    value = source.get(name)
    try:
        value = float(value)
    except (TypeError, ValueError):
        return None
    return value if np.isfinite(value) else None


def _bootstrap_ci(
    values: np.ndarray,
    n_resamples: int = 10000,
    alpha: float = 0.05,
    rng_seed: int = 12345,
) -> tuple[float, float]:
    rng = np.random.default_rng(rng_seed)
    idx = rng.integers(0, values.size, size=(n_resamples, values.size))
    means = values[idx].mean(axis=1)
    return (
        float(np.quantile(means, alpha / 2.0)),
        float(np.quantile(means, 1.0 - alpha / 2.0)),
    )


def _latest_per_seed(paths: List[str]) -> Dict[int, str]:
    """Keep only the newest results file per seed."""
    by_seed: Dict[int, str] = {}
    for path in sorted(paths, key=os.path.getmtime):
        seed = _seed_from_path(path)
        if seed is not None:
            by_seed[seed] = path
    return by_seed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--label", required=True, help="Name for this arm/run group in the output.")
    parser.add_argument(
        "--results_glob",
        required=True,
        nargs="+",
        help="Glob pattern(s) for per-seed evaluation JSONs (evaluation_tiers_*.json).",
    )
    parser.add_argument("--metrics", nargs="+", default=DEFAULT_METRICS)
    parser.add_argument("--output_dir", default="results/seed_summaries")
    parser.add_argument("--bootstrap_resamples", type=int, default=10000)
    parser.add_argument("--bootstrap_seed", type=int, default=12345)
    parser.add_argument(
        "--deterministic",
        action="store_true",
        help=(
            "Treat seed outputs as replication checks for one deterministic "
            "investor path. No seed bootstrap CI is produced."
        ),
    )
    parser.add_argument(
        "--deterministic_tolerance",
        type=float,
        default=1e-9,
        help="Maximum allowed max-min spread for deterministic metric replicas.",
    )
    args = parser.parse_args()

    paths: List[str] = []
    for pattern in args.results_glob:
        pattern_path = pattern if os.path.isabs(pattern) else str(PROJECT_ROOT / pattern)
        paths.extend(glob.glob(pattern_path, recursive=True))
    by_seed = _latest_per_seed(paths)
    if not by_seed:
        print(f"No evaluation JSONs matched: {args.results_glob}", file=sys.stderr)
        return 1

    per_seed_values: Dict[str, Dict[int, float]] = {name: {} for name in args.metrics}
    for seed, path in sorted(by_seed.items()):
        try:
            with open(path, "r", encoding="utf-8") as f:
                payload = json.load(f)
        except Exception as exc:
            print(f"[WARN] Failed to read {path}: {exc}", file=sys.stderr)
            continue
        tier_metrics = _extract_tier_metrics(payload)
        if not tier_metrics:
            print(f"[WARN] No tier metrics in {path}", file=sys.stderr)
            continue
        for name in args.metrics:
            value = _metric_value(tier_metrics, name)
            if value is not None:
                per_seed_values[name][seed] = value

    rows: List[Dict[str, Any]] = []
    for name in args.metrics:
        values_by_seed = per_seed_values[name]
        values = np.asarray(list(values_by_seed.values()), dtype=np.float64)
        if values.size == 0:
            rows.append({"label": args.label, "metric": name, "n_seeds": 0})
            continue
        row: Dict[str, Any] = {
            "label": args.label,
            "metric": name,
            "n_seeds": int(values.size),
            "seeds": ",".join(str(s) for s in sorted(values_by_seed)),
            "mean": float(np.mean(values)),
            "std": float(np.std(values, ddof=1)) if values.size > 1 else 0.0,
            "min": float(np.min(values)),
            "max": float(np.max(values)),
            "median": float(np.median(values)),
            "uncertainty_unit": "deterministic_replication_check" if args.deterministic else "training_seed",
        }
        if args.deterministic:
            spread = float(np.max(values) - np.min(values))
            row["deterministic_replica_spread"] = spread
            row["deterministic_replica_consistent"] = bool(
                spread <= float(args.deterministic_tolerance)
            )
        elif values.size > 1:
            lo, hi = _bootstrap_ci(
                values,
                n_resamples=int(args.bootstrap_resamples),
                rng_seed=int(args.bootstrap_seed),
            )
            row["bootstrap_ci95_low"] = lo
            row["bootstrap_ci95_high"] = hi
        rows.append(row)

    output_dir = Path(args.output_dir)
    if not output_dir.is_absolute():
        output_dir = PROJECT_ROOT / output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    json_path = output_dir / f"seed_summary_{args.label}.json"
    csv_path = output_dir / f"seed_summary_{args.label}.csv"
    payload_out = {
        "label": args.label,
        "results_glob": list(args.results_glob),
        "n_result_files": len(by_seed),
        "result_files": {str(seed): path for seed, path in sorted(by_seed.items())},
        "bootstrap_resamples": int(args.bootstrap_resamples),
        "deterministic": bool(args.deterministic),
        "uncertainty_note": (
            "Deterministic seed outputs are replication checks; use a common "
            "moving-block bootstrap over daily investor returns for market-path uncertainty."
            if args.deterministic
            else "Bootstrap intervals quantify training-seed uncertainty only, not market-path uncertainty."
        ),
        "rows": rows,
    }
    with json_path.open("w", encoding="utf-8") as f:
        json.dump(payload_out, f, indent=2)
    fieldnames = sorted({key for row in rows for key in row})
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Wrote {json_path}")
    print(f"Wrote {csv_path}")
    for row in rows:
        if row.get("n_seeds"):
            ci = (
                f" CI95=[{row['bootstrap_ci95_low']:.4g}, {row['bootstrap_ci95_high']:.4g}]"
                if "bootstrap_ci95_low" in row
                else ""
            )
            print(f"  {row['metric']}: mean={row['mean']:.4g} std={row['std']:.4g} n={row['n_seeds']}{ci}")
        else:
            print(f"  {row['metric']}: no values found")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
